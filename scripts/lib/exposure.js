/**
 * Returns a function giving the exposure of a district feature, after checking that every id in
 * the tables above exists among `districtIds`. Populations outside the Census table are estimated
 * from area and state density with a stable per-district jitter.
 */
export function exposureLookup(districtIds) {
  const tableIds = [...Object.keys(POPULATION_2011), ...LANDSLIDE_DISTRICTS, ...Object.values(LARGE_DAMS)];
  const unknown = tableIds.filter((id) => !districtIds.has(id));
  if (unknown.length) throw new Error(`Exposure tables: unknown district ids ${unknown.join(', ')}`);

  return (feature) => {
    const { id, state } = feature.properties;
    const jitter = 0.75 + 0.55 * seededRandom(SEED ^ hashString(id))();
    return {
      population: POPULATION_2011[id] ?? Math.round((areaKm2(feature) * STATE_DENSITY[state] * jitter) / 100) * 100,
      landslideProne: LANDSLIDE_STATES.has(state) || LANDSLIDE_DISTRICTS.has(id),
      dams: Object.keys(LARGE_DAMS).filter((dam) => LARGE_DAMS[dam] === id),
    };
  };
}
